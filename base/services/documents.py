"""Validation and storage of the documents attached to the objects.

The type of an upload is read from its first bytes, never from the name or the
content type sent by the browser.
"""

import datetime
from pathlib import Path

from django.conf import settings
from django.contrib.contenttypes.models import ContentType
from django.core.exceptions import ValidationError
from django.core.files.base import ContentFile, File
from django.db import models
from django.utils.translation import gettext as _

from base.models import Document

#: Accepted file types: MIME type → extensions.
ALLOWED_TYPES = {
    "application/pdf": {".pdf"},
    "image/jpeg": {".jpg", ".jpeg"},
    "image/png": {".png"},
    "image/webp": {".webp"},
    "image/heic": {".heic", ".heif"},
}

_HEIC_BRANDS = {b"heic", b"heix", b"hevc", b"hevx", b"mif1", b"msf1"}


def sniff_mime_type(head: bytes) -> str | None:
    """MIME type of a file from its first bytes, None when not accepted."""
    if head.startswith(b"%PDF-"):
        return "application/pdf"
    if head.startswith(b"\xff\xd8\xff"):
        return "image/jpeg"
    if head.startswith(b"\x89PNG\r\n\x1a\n"):
        return "image/png"
    if head[:4] == b"RIFF" and head[8:12] == b"WEBP":
        return "image/webp"
    if head[4:8] == b"ftyp" and head[8:12] in _HEIC_BRANDS:
        return "image/heic"
    return None


def validate_upload(upload: File) -> str:
    """Check the size and type of *upload*; its MIME type."""
    if upload.size > settings.DOCUMENT_MAX_SIZE:
        raise ValidationError(
            _("The file is too large (%(max)d MB maximum).")
            % {"max": settings.DOCUMENT_MAX_SIZE // (1024 * 1024)}
        )
    upload.seek(0)
    head = upload.read(16)
    upload.seek(0)
    mime_type = sniff_mime_type(head)
    suffix = Path(upload.name or "").suffix.lower()
    if mime_type is None or suffix not in ALLOWED_TYPES[mime_type]:
        raise ValidationError(
            _("Only PDF, JPEG, PNG, WebP and HEIC files are accepted.")
        )
    return mime_type


def attach_upload(
    obj: models.Model,
    upload: File,
    *,
    title: str = "",
    kind: str = Document.Kind.OTHER,
    valid_until: datetime.date | None = None,
    notes: str = "",
    user=None,
) -> Document:
    """Validate *upload* and store it as a document of *obj*."""
    mime_type = validate_upload(upload)
    name = Path(upload.name or "file").name
    document = Document(
        content_object=obj,
        kind=kind,
        title=title or Path(name).stem,
        original_name=name,
        mime_type=mime_type,
        size=upload.size,
        valid_until=valid_until,
        notes=notes,
        uploaded_by=user,
    )
    document.file.save(name, upload, save=False)
    document.save()
    return document


def attach_pdf(
    obj: models.Model,
    content: bytes,
    *,
    filename: str,
    title: str,
    kind: str,
    user=None,
) -> Document:
    """Store a PDF generated by the application as a document of *obj*."""
    document = Document(
        content_object=obj,
        kind=kind,
        title=title,
        original_name=filename,
        mime_type="application/pdf",
        size=len(content),
        uploaded_by=user,
    )
    document.file.save(filename, ContentFile(content), save=False)
    document.save()
    return document


def documents_of(obj: models.Model):
    """Documents attached to *obj*, newest first."""
    return Document.objects.filter(
        content_type=ContentType.objects.get_for_model(obj), object_id=obj.pk
    )
